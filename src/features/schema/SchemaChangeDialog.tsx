import { useEffect, useState, type ReactNode } from 'react';

import type { DbError } from '@/bindings/DbError';
import type { SchemaChange } from '@/bindings/SchemaChange';
import { Alert, Button, Dialog, ErrorAlert, Spinner } from '@/components/ui';
import { SqlViewer } from '@/features/editor/SqlViewer';
import { toAppError } from '@/lib/errors';
import { api } from '@/lib/ipc';
import { guarded, useUi } from '@/stores/ui';
import { useWorkspace } from '@/stores/workspace';

interface SchemaChangeDialogProps {
  title: string;
  /** The changes the form describes, or a message saying what is missing. */
  changes: SchemaChange[] | string;
  children?: ReactNode;
  onClose: () => void;
  onApplied: () => void;
  /** Skip the form step (drops): go straight to the reviewed SQL. */
  direct?: boolean;
}

/**
 * Form → reviewed SQL → apply. The SQL shown is generated by the backend,
 * which builds it again from the same changes when applying; destructive and
 * production changes still go through the confirmation dialog.
 */
export function SchemaChangeDialog({ title, changes, children, onClose, onApplied, direct }: SchemaChangeDialogProps) {
  const session = useWorkspace((s) => s.session)!;
  const [sql, setSql] = useState<string | null>(null);
  const [step, setStep] = useState<'form' | 'preview'>(direct ? 'preview' : 'form');
  const [error, setError] = useState<DbError | null>(null);
  const [busy, setBusy] = useState(false);
  const sid = { sessionId: session.session_id };
  const ready = Array.isArray(changes);

  const preview = async () => {
    if (!ready) return;
    setBusy(true);
    setError(null);
    try {
      setSql(await api.schemaChangePreview(sid, changes));
      setStep('preview');
    } catch (e) {
      setError(toAppError(e).info);
    } finally {
      setBusy(false);
    }
  };

  useEffect(() => {
    if (direct) void preview();
    // Drops have no form: generate their SQL once, on open.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const apply = async () => {
    if (!ready) return;
    setBusy(true);
    setError(null);
    try {
      const report = await guarded((c) => api.applySchemaChanges(sid, changes, c));
      if (report) {
        useUi.getState().toast(`Applied ${report.statements} statement${report.statements === 1 ? '' : 's'}.`, 'positive');
        onApplied();
        onClose();
      }
    } catch (e) {
      setError(toAppError(e).info);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog
      title={title}
      wide
      onClose={onClose}
      footer={
        step === 'form' ? (
          <>
            <Button onClick={onClose}>Cancel</Button>
            <Button variant="primary" busy={busy} disabled={!ready} onClick={() => void preview()}>
              Preview SQL
            </Button>
          </>
        ) : (
          <>
            {!direct && <Button onClick={() => setStep('form')}>Back</Button>}
            <Button onClick={() => sql && useWorkspace.getState().openQueryTab({ sql, title: 'schema-change.sql' })} disabled={!sql}>
              Open in editor
            </Button>
            <Button onClick={onClose}>Cancel</Button>
            <Button variant="primary" busy={busy} disabled={!sql} onClick={() => void apply()}>
              Apply
            </Button>
          </>
        )
      }
    >
      {step === 'form' ? (
        <>
          {children}
          {!ready && <p className="ink-3" style={{ marginTop: 8 }}>{changes}</p>}
        </>
      ) : sql === null ? (
        <Spinner label="Generating SQL" />
      ) : (
        <>
          <Alert tone="info">This SQL runs only when you press Apply. Review it first.</Alert>
          <div style={{ height: 260, marginTop: 10, border: '1px solid var(--line)', borderRadius: 'var(--radius)' }}>
            <SqlViewer value={sql} flavor={session.flavor} label="Schema change SQL" />
          </div>
        </>
      )}
      {error && (
        <div style={{ marginTop: 10 }}>
          <ErrorAlert error={error} />
        </div>
      )}
    </Dialog>
  );
}
