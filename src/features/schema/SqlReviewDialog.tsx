import { useEffect, useState, type ReactNode } from 'react';

import type { Confirmation } from '@/bindings/Confirmation';
import type { DbError } from '@/bindings/DbError';
import type { Guarded } from '@/bindings/Guarded';
import { Alert, Button, Dialog, ErrorAlert, Spinner } from '@/components/ui';
import { SqlViewer } from '@/features/editor/SqlViewer';
import { toAppError } from '@/lib/errors';
import { guarded, useUi } from '@/stores/ui';
import { useWorkspace } from '@/stores/workspace';

export interface SqlReviewDialogProps<T> {
  title: string;
  /** Why the form cannot be reviewed yet, or `null` when it is complete. */
  missing: string | null;
  /** SQL for review, generated by the backend. */
  preview: () => Promise<string>;
  /** Builds the SQL again in the backend and runs it, asking for confirmation when needed. */
  apply: (confirmation: Confirmation | null) => Promise<Guarded<T>>;
  /** Toast shown after a successful apply. */
  done: (result: T) => string;
  children?: ReactNode;
  onClose: () => void;
  onApplied: () => void;
  /** Skip the form step (drops): go straight to the reviewed SQL. */
  direct?: boolean;
  /** The reviewed SQL can be opened in an editor (not when it masks a password). */
  editable?: boolean;
  /** Shown above the SQL, e.g. that passwords are masked. */
  note?: ReactNode;
  /** Title of the editor tab "Open in editor" opens. */
  fileName?: string;
}

/**
 * Form → reviewed SQL → apply (T6.4). The SQL shown is generated by the
 * backend, which builds it again from the same input when applying;
 * destructive and production changes still go through the confirmation dialog.
 */
export function SqlReviewDialog<T>({
  title,
  missing,
  preview,
  apply,
  done,
  children,
  onClose,
  onApplied,
  direct,
  editable = true,
  note,
  fileName = 'schema-change.sql',
}: SqlReviewDialogProps<T>) {
  const session = useWorkspace((s) => s.session)!;
  const [sql, setSql] = useState<string | null>(null);
  const [step, setStep] = useState<'form' | 'preview'>(direct ? 'preview' : 'form');
  const [error, setError] = useState<DbError | null>(null);
  const [busy, setBusy] = useState(false);
  const ready = missing === null;

  const review = async () => {
    if (!ready) return;
    setBusy(true);
    setError(null);
    try {
      setSql(await preview());
      setStep('preview');
    } catch (e) {
      setError(toAppError(e).info);
    } finally {
      setBusy(false);
    }
  };

  useEffect(() => {
    if (direct) void review();
    // Drops have no form: generate their SQL once, on open.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const run = async () => {
    if (!ready) return;
    setBusy(true);
    setError(null);
    try {
      const result = await guarded(apply);
      if (result !== null) {
        useUi.getState().toast(done(result), 'positive');
        onApplied();
        onClose();
      }
    } catch (e) {
      setError(toAppError(e).info);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog
      title={title}
      wide
      onClose={onClose}
      footer={
        step === 'form' ? (
          <>
            <Button onClick={onClose}>Cancel</Button>
            <Button variant="primary" busy={busy} disabled={!ready} onClick={() => void review()}>
              Preview SQL
            </Button>
          </>
        ) : (
          <>
            {!direct && <Button onClick={() => setStep('form')}>Back</Button>}
            {editable && (
              <Button
                onClick={() => sql && useWorkspace.getState().openQueryTab({ sql, title: fileName })}
                disabled={!sql}
              >
                Open in editor
              </Button>
            )}
            <Button onClick={onClose}>Cancel</Button>
            <Button variant="primary" busy={busy} disabled={!sql} onClick={() => void run()}>
              Apply
            </Button>
          </>
        )
      }
    >
      {step === 'form' ? (
        <>
          {children}
          {missing && (
            <p className="ink-3" style={{ marginTop: 8 }}>
              {missing}
            </p>
          )}
        </>
      ) : sql === null ? (
        <Spinner label="Generating SQL" />
      ) : (
        <>
          <Alert tone="info">This SQL runs only when you press Apply. Review it first.{note && <> {note}</>}</Alert>
          <div style={{ height: 260, marginTop: 10, border: '1px solid var(--line)', borderRadius: 'var(--radius)' }}>
            <SqlViewer value={sql} flavor={session.flavor} label="Reviewed SQL" />
          </div>
        </>
      )}
      {error && (
        <div style={{ marginTop: 10 }}>
          <ErrorAlert error={error} />
        </div>
      )}
    </Dialog>
  );
}
