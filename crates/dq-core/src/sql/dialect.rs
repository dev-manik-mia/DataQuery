//! Identifier and literal quoting per engine.

use std::fmt::Write;

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::node::ObjectRef;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum SqlFlavor {
    Postgres,
    Mysql,
    /// T-SQL (SQL Server).
    Sqlserver,
    /// Oracle SQL and PL/SQL.
    Oracle,
    /// `ClickHouse` SQL.
    Clickhouse,
    /// `DuckDB`: `PostgreSQL`-style SQL.
    Duckdb,
    /// Snowflake SQL and Snowflake Scripting.
    Snowflake,
    /// `MongoDB` shell statements: `db.orders.find({ … })`, `show collections`, `use app`.
    Mongodb,
    /// `PartiQL` as `DynamoDB` runs it: `SELECT * FROM "orders" WHERE "pk" = ?`.
    Partiql,
}

impl SqlFlavor {
    /// Lexes like `PostgreSQL` (dollar quotes, `E''`, nested comments, `$n`).
    pub fn postgres_like(self) -> bool {
        matches!(self, Self::Postgres | Self::Duckdb)
    }

    /// Statements are not SQL: the document engines' own languages.
    pub fn is_document(self) -> bool {
        matches!(self, Self::Mongodb | Self::Partiql)
    }
}

/// Engine-specific SQL spelling. Every identifier that ends up in generated SQL
/// goes through [`Dialect::quote_ident`]; values only ever travel as parameters,
/// except in human-readable previews built with [`Dialect::quote_literal`].
pub trait Dialect: Send + Sync {
    fn flavor(&self) -> SqlFlavor;

    /// Always-quoted identifier, safe for any input.
    fn quote_ident(&self, ident: &str) -> String;

    /// Quotes only when needed. Used for names shown to and copied by the user.
    fn display_ident(&self, ident: &str) -> String {
        if self.needs_quotes(ident) { self.quote_ident(ident) } else { ident.to_owned() }
    }

    fn needs_quotes(&self, ident: &str) -> bool;

    /// String literal for previews. Never used to build executed SQL.
    fn quote_literal(&self, value: &str) -> String;

    /// Placeholder for the `index`-th (1-based) text parameter targeting a
    /// column of `column_type`.
    fn placeholder(&self, index: usize, column_type: &str) -> String;

    /// Expression that reads a column as text for display when its type has no
    /// native decoder.
    fn cast_to_text(&self, quoted_column: &str) -> String;

    /// The type supports `=` against a text parameter, so it can help identify a row.
    fn comparable(&self, data_type: &str) -> bool;

    /// Case-insensitive `LIKE` of a column's text form against a pattern parameter.
    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String;

    /// Expression that reads a column of `data_type` as text. Engines whose
    /// special types need more than a cast override this.
    fn text_expr(&self, quoted_column: &str, _data_type: &str) -> String {
        self.cast_to_text(quoted_column)
    }

    /// The container that qualifies an object name: the schema (`PostgreSQL`,
    /// SQL Server, Oracle, `DuckDB`, Snowflake) or the database (`MySQL`, `ClickHouse`).
    fn container<'a>(&self, object: &'a ObjectRef) -> Option<&'a str> {
        match self.flavor() {
            SqlFlavor::Mysql | SqlFlavor::Clickhouse | SqlFlavor::Mongodb => Some(object.database.as_str()),
            SqlFlavor::Partiql => None,
            SqlFlavor::Postgres
            | SqlFlavor::Sqlserver
            | SqlFlavor::Oracle
            | SqlFlavor::Duckdb
            | SqlFlavor::Snowflake => object.schema.as_deref(),
        }
        .filter(|c| !c.is_empty())
    }

    /// Engines whose connections can reach several databases name the
    /// database too (`db.schema.table`) in executed SQL.
    fn qualifies_database(&self) -> bool {
        false
    }

    /// Restricts `sql` to `limit` rows after skipping `offset`. `ordered` says
    /// whether `sql` already ends with `ORDER BY`.
    fn paginate(&self, sql: &str, ordered: bool, offset: u64, limit: u64) -> String {
        let _ = ordered;
        if offset == 0 { format!("{sql} LIMIT {limit}") } else { format!("{sql} LIMIT {limit} OFFSET {offset}") }
    }

    /// Placeholder shown in generated templates for the `n`-th value.
    fn template_placeholder(&self, n: usize) -> String;

    /// Statement that opens a transaction on the query connection.
    fn begin_transaction(&self) -> &'static str {
        "BEGIN"
    }

    /// Column clause that makes a column generate its own values, if the engine has one.
    fn identity_clause(&self) -> Option<&'static str> {
        Some(" GENERATED BY DEFAULT AS IDENTITY")
    }

    /// A failed statement aborts the open transaction until `ROLLBACK`.
    fn aborts_transaction_on_error(&self) -> bool {
        self.flavor().postgres_like()
    }

    /// Literal for a binary value given as hex, for SQL exports.
    fn binary_literal(&self, hex: &str) -> String;

    /// Literal for a boolean, for SQL exports.
    fn bool_literal(&self, value: bool) -> &'static str {
        if value { "TRUE" } else { "FALSE" }
    }

    /// Bound parameters the engine accepts in one statement.
    fn max_params(&self) -> usize {
        65_535
    }

    /// Rows one multi-row `INSERT … VALUES` may carry.
    fn max_insert_rows(&self) -> usize {
        usize::MAX
    }

    /// `INSERT` of several rows. `tuples` are parenthesised value lists.
    fn multi_insert(&self, table: &str, columns: &str, tuples: &[String]) -> String {
        format!("INSERT INTO {table} ({columns}) VALUES {}", tuples.join(", "))
    }

    /// `INSERT` that stores a row of defaults. `first_column` is a quoted column of the table.
    fn insert_defaults(&self, table: &str, _first_column: Option<&str>) -> String {
        format!("INSERT INTO {table} DEFAULT VALUES")
    }

    /// Fully quoted `schema.table` (Postgres), `` `db`.`table` `` (MySQL) or
    /// `db.schema.table` where [`Dialect::qualifies_database`].
    fn quoted_name(&self, object: &ObjectRef) -> String {
        let name = join(self.container(object), &object.name, |s| self.quote_ident(s));
        if self.qualifies_database() && !object.database.is_empty() && object.schema.is_some() {
            format!("{}.{name}", self.quote_ident(&object.database))
        } else {
            name
        }
    }

    /// Minimal-quoted name for copying and generated templates.
    fn display_name(&self, object: &ObjectRef) -> String {
        join(self.container(object), &object.name, |s| self.display_ident(s))
    }
}

