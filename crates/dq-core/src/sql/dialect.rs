impl Dialect for PostgresDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Postgres
    }

    fn quote_ident(&self, ident: &str) -> String {
        format!("\"{}\"", ident.replace('"', "\"\""))
    }

    fn needs_quotes(&self, ident: &str) -> bool {
        let mut chars = ident.chars();
        let simple = chars.next().is_some_and(|c| c.is_ascii_lowercase() || c == '_')
            && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '$');
        !simple || is_reserved(ident, POSTGRES_RESERVED)
    }

    fn quote_literal(&self, value: &str) -> String {
        format!("'{}'", value.replace('\'', "''"))
    }

    fn placeholder(&self, index: usize, column_type: &str) -> String {
        // Text parameters are converted by the server using the column's own
        // input function, so exact values (int8, numeric, timestamptz) survive.
        format!("${index}::text::{column_type}")
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        format!("{quoted_column}::text")
    }

    fn comparable(&self, data_type: &str) -> bool {
        const NO_EQUALITY: &[&str] = &["json", "xml", "point", "line", "lseg", "box", "path", "polygon", "circle"];
        let base = data_type.split(['(', '[']).next().unwrap_or(data_type).trim();
        !NO_EQUALITY.contains(&base)
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        format!("{quoted_column}::text ILIKE {placeholder}")
    }

    fn template_placeholder(&self, n: usize) -> String {
        format!("${n}")
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("'\\x{hex}'::bytea")
    }
}

impl Dialect for MysqlDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Mysql
    }

    fn quote_ident(&self, ident: &str) -> String {
        format!("`{}`", ident.replace('`', "``"))
    }

    fn needs_quotes(&self, ident: &str) -> bool {
        let simple = !ident.is_empty()
            && ident.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
            && !ident.chars().all(|c| c.is_ascii_digit());
        !simple || is_reserved(ident, MYSQL_RESERVED)
    }

    fn quote_literal(&self, value: &str) -> String {
        format!("'{}'", value.replace('\\', "\\\\").replace('\'', "''"))
    }

    fn placeholder(&self, _index: usize, _column_type: &str) -> String {
        "?".to_owned()
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        format!("CAST({quoted_column} AS CHAR)")
    }

    fn comparable(&self, data_type: &str) -> bool {
        // JSON compares as a document, never equal to a text parameter.
        !data_type.eq_ignore_ascii_case("json")
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        // Case-insensitive under the default (`_ci`) connection collations.
        format!("CAST({quoted_column} AS CHAR) LIKE {placeholder}")
    }

    fn template_placeholder(&self, _n: usize) -> String {
        "?".to_owned()
    }

    fn begin_transaction(&self) -> &'static str {
        "START TRANSACTION"
    }

    fn identity_clause(&self) -> Option<&'static str> {
        Some(" AUTO_INCREMENT")
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("X'{hex}'")
    }

    fn insert_defaults(&self, table: &str, _first_column: Option<&str>) -> String {
        format!("INSERT INTO {table} () VALUES ()")
    }
}

/// Base name of a type, lower-cased: `nvarchar(50)` → `nvarchar`.
fn base_type(data_type: &str) -> String {
    data_type.split(['(', '[']).next().unwrap_or(data_type).trim().to_ascii_lowercase()
}

impl Dialect for SqlServerDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Sqlserver
    }

    fn quote_ident(&self, ident: &str) -> String {
        format!("[{}]", ident.replace(']', "]]"))
    }

    fn needs_quotes(&self, ident: &str) -> bool {
        let mut chars = ident.chars();
        let simple = chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
            && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
        !simple || is_reserved(ident, SQLSERVER_RESERVED)
    }

    fn quote_literal(&self, value: &str) -> String {
        format!("N'{}'", value.replace('\'', "''"))
    }

    fn placeholder(&self, index: usize, column_type: &str) -> String {
        // Parameters travel as text; the cast converts them with the column's own
        // rules so comparisons stay sargable and exact.
        match base_type(column_type).as_str() {
            "" | "text" | "ntext" | "nvarchar" => format!("@P{index}"),
            _ => format!("CAST(@P{index} AS {column_type})"),
        }
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        format!("CONVERT(nvarchar(max), {quoted_column})")
    }

    fn text_expr(&self, quoted_column: &str, data_type: &str) -> String {
        match base_type(data_type).as_str() {
            // CLR types have no conversion to text, only `ToString()`.
            "geography" | "geometry" | "hierarchyid" => format!("{quoted_column}.ToString()"),
            _ => self.cast_to_text(quoted_column),
        }
    }

    fn comparable(&self, data_type: &str) -> bool {
        const NO_EQUALITY: &[&str] =
            &["text", "ntext", "image", "xml", "geography", "geometry", "sql_variant", "timestamp", "rowversion"];
        !NO_EQUALITY.contains(&base_type(data_type).as_str())
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        // Case-insensitive under the default (`_CI_`) collations.
        format!("CONVERT(nvarchar(max), {quoted_column}) LIKE {placeholder} ESCAPE '\\'")
    }

    fn paginate(&self, sql: &str, ordered: bool, offset: u64, limit: u64) -> String {
        // OFFSET … FETCH needs an ORDER BY.
        let order = if ordered { "" } else { " ORDER BY (SELECT NULL)" };
        format!("{sql}{order} OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY")
    }

    fn template_placeholder(&self, n: usize) -> String {
        format!("@P{n}")
    }

    fn begin_transaction(&self) -> &'static str {
        "BEGIN TRANSACTION"
    }

    fn identity_clause(&self) -> Option<&'static str> {
        Some(" IDENTITY(1,1)")
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("0x{hex}")
    }

    fn bool_literal(&self, value: bool) -> &'static str {
        if value { "1" } else { "0" }
    }

    fn max_params(&self) -> usize {
        2_000
    }

    fn max_insert_rows(&self) -> usize {
        1_000
    }
}

impl Dialect for OracleDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Oracle
    }

    /// Oracle has no escape for `"` inside a quoted name, and no name contains
    /// one; a doubled quote makes the statement fail to parse instead of
    /// changing its meaning.
    fn quote_ident(&self, ident: &str) -> String {
        format!("\"{}\"", ident.replace('"', "\"\""))
    }

    /// Unquoted names are upper-cased by the server, so anything else needs quotes.
    fn needs_quotes(&self, ident: &str) -> bool {
        let mut chars = ident.chars();
        let simple = chars.next().is_some_and(|c| c.is_ascii_uppercase())
            && chars.all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || matches!(c, '_' | '$' | '#'));
        !simple || is_reserved(ident, ORACLE_RESERVED)
    }

    fn quote_literal(&self, value: &str) -> String {
        format!("'{}'", value.replace('\'', "''"))
    }

    /// Text parameters convert implicitly; the session fixes the NLS formats
    /// so numbers, dates and timestamps round-trip.
    fn placeholder(&self, index: usize, _column_type: &str) -> String {
        format!(":{index}")
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        format!("TO_CHAR({quoted_column})")
    }

    fn text_expr(&self, quoted_column: &str, data_type: &str) -> String {
        match base_type(data_type).as_str() {
            "xmltype" | "sys.xmltype" => format!("XMLSERIALIZE(CONTENT {quoted_column} AS CLOB)"),
            "sdo_geometry" | "mdsys.sdo_geometry" => format!("SDO_UTIL.TO_WKTGEOMETRY({quoted_column})"),
            "json" => format!("JSON_SERIALIZE({quoted_column} RETURNING CLOB)"),
            _ => self.cast_to_text(quoted_column),
        }
    }

    fn comparable(&self, data_type: &str) -> bool {
        const NO_EQUALITY: &[&str] =
            &["clob", "nclob", "blob", "bfile", "long", "long raw", "xmltype", "sdo_geometry", "json", "vector"];
        !NO_EQUALITY.contains(&base_type(data_type).as_str())
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        format!("LOWER(TO_CHAR({quoted_column})) LIKE LOWER({placeholder}) ESCAPE '\\'")
    }

    fn paginate(&self, sql: &str, _ordered: bool, offset: u64, limit: u64) -> String {
        if offset == 0 {
            format!("{sql} FETCH FIRST {limit} ROWS ONLY")
        } else {
            format!("{sql} OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY")
        }
    }

    fn template_placeholder(&self, n: usize) -> String {
        format!(":{n}")
    }

    /// Oracle opens transactions implicitly; this marks the start of one the
    /// user commits explicitly.
    fn begin_transaction(&self) -> &'static str {
        "SET TRANSACTION READ WRITE"
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("HEXTORAW('{hex}')")
    }

    fn bool_literal(&self, value: bool) -> &'static str {
        if value { "1" } else { "0" }
    }

    fn max_params(&self) -> usize {
        // The server allows 65,535 binds; stay well inside it.
        32_000
    }

    /// Oracle 19c has no multi-row `VALUES`; `INSERT ALL` inserts the rows in one statement.
    fn multi_insert(&self, table: &str, columns: &str, tuples: &[String]) -> String {
        if tuples.len() == 1 {
            return format!("INSERT INTO {table} ({columns}) VALUES {}", tuples[0]);
        }
        let mut sql = String::from("INSERT ALL");
        for t in tuples {
            let _ = write!(sql, " INTO {table} ({columns}) VALUES {t}");
        }
        sql.push_str(" SELECT 1 FROM DUAL");
        sql
    }

    fn insert_defaults(&self, table: &str, first_column: Option<&str>) -> String {
        match first_column {
            Some(c) => format!("INSERT INTO {table} ({c}) VALUES (DEFAULT)"),
            None => format!("INSERT INTO {table} DEFAULT VALUES"),
        }
    }
}

/// Unwraps `Nullable(…)` and `LowCardinality(…)` around a `ClickHouse` type.
fn clickhouse_base(data_type: &str) -> &str {
    let mut t = data_type.trim();
    for wrapper in ["LowCardinality(", "Nullable("] {
        if let Some(inner) = t.strip_prefix(wrapper).and_then(|r| r.strip_suffix(')')) {
            t = inner.trim();
        }
    }
    t
}

impl Dialect for ClickhouseDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Clickhouse
    }

    fn quote_ident(&self, ident: &str) -> String {
        format!("`{}`", ident.replace('\\', "\\\\").replace('`', "\\`"))
    }

    fn needs_quotes(&self, ident: &str) -> bool {
        let simple = ident.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
            && ident.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        !simple || is_reserved(ident, CLICKHOUSE_RESERVED)
    }

    fn quote_literal(&self, value: &str) -> String {
        format!("'{}'", value.replace('\\', "\\\\").replace('\'', "\\'"))
    }

    /// Server-side query parameters, sent as text and converted to the column's type.
    fn placeholder(&self, index: usize, column_type: &str) -> String {
        match clickhouse_base(column_type) {
            "text" | "String" => format!("{{p{index}:Nullable(String)}}"),
            base => format!("CAST({{p{index}:Nullable(String)}} AS Nullable({base}))"),
        }
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        format!("toString({quoted_column})")
    }

    fn comparable(&self, data_type: &str) -> bool {
        let base = clickhouse_base(data_type);
        !["Map(", "Object(", "JSON", "AggregateFunction(", "Array(", "Tuple(", "Nested("]
            .iter()
            .any(|p| base.starts_with(p))
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        format!("toString({quoted_column}) ILIKE {placeholder}")
    }

    fn template_placeholder(&self, n: usize) -> String {
        format!("{{p{n}:String}}")
    }

    fn identity_clause(&self) -> Option<&'static str> {
        None
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("unhex('{hex}')")
    }

    fn max_params(&self) -> usize {
        // Parameters travel in the request URL.
        1_000
    }
}

impl Dialect for DuckdbDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Duckdb
    }

    fn quote_ident(&self, ident: &str) -> String {
        PostgresDialect.quote_ident(ident)
    }

    fn needs_quotes(&self, ident: &str) -> bool {
        PostgresDialect.needs_quotes(ident)
    }

    fn quote_literal(&self, value: &str) -> String {
        PostgresDialect.quote_literal(value)
    }

    fn placeholder(&self, index: usize, column_type: &str) -> String {
        if column_type == "text" { format!("${index}") } else { format!("CAST(${index} AS {column_type})") }
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        format!("CAST({quoted_column} AS VARCHAR)")
    }

    fn comparable(&self, data_type: &str) -> bool {
        let base = base_type(data_type);
        !matches!(base.as_str(), "json" | "map" | "struct" | "union") && !data_type.ends_with("[]")
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        format!("CAST({quoted_column} AS VARCHAR) ILIKE {placeholder} ESCAPE '\\'")
    }

    /// Attached databases are reached by name, so executed SQL names the database.
    fn qualifies_database(&self) -> bool {
        true
    }

    fn template_placeholder(&self, n: usize) -> String {
        format!("${n}")
    }

    fn begin_transaction(&self) -> &'static str {
        "BEGIN TRANSACTION"
    }

    fn identity_clause(&self) -> Option<&'static str> {
        None
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("from_hex('{hex}')")
    }
}

impl Dialect for SnowflakeDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Snowflake
    }

    fn quote_ident(&self, ident: &str) -> String {
        format!("\"{}\"", ident.replace('"', "\"\""))
    }

    /// Unquoted names are upper-cased, so anything else needs quotes.
    fn needs_quotes(&self, ident: &str) -> bool {
        let mut chars = ident.chars();
        let simple = chars.next().is_some_and(|c| c.is_ascii_uppercase() || c == '_')
            && chars.all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_' || c == '$');
        !simple || is_reserved(ident, SNOWFLAKE_RESERVED)
    }

    /// Snowflake processes backslash escapes inside string literals.
    fn quote_literal(&self, value: &str) -> String {
        format!("'{}'", value.replace('\\', "\\\\").replace('\'', "''"))
    }

    fn placeholder(&self, index: usize, column_type: &str) -> String {
        if column_type == "text" { format!(":{index}") } else { format!("CAST(:{index} AS {column_type})") }
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        format!("TO_VARCHAR({quoted_column})")
    }

    fn text_expr(&self, quoted_column: &str, data_type: &str) -> String {
        match base_type(data_type).as_str() {
            "variant" | "object" | "array" => format!("TO_JSON({quoted_column})"),
            "geography" | "geometry" => format!("ST_ASWKT({quoted_column})"),
            _ => self.cast_to_text(quoted_column),
        }
    }

    fn comparable(&self, data_type: &str) -> bool {
        !matches!(base_type(data_type).as_str(), "variant" | "object" | "array" | "geography" | "geometry" | "vector")
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        format!("TO_VARCHAR({quoted_column}) ILIKE {placeholder} ESCAPE '\\\\'")
    }

    /// Names are resolved in the session's current database otherwise.
    fn qualifies_database(&self) -> bool {
        true
    }

    fn template_placeholder(&self, n: usize) -> String {
        format!(":{n}")
    }

    fn begin_transaction(&self) -> &'static str {
        "BEGIN TRANSACTION"
    }

    fn identity_clause(&self) -> Option<&'static str> {
        Some(" IDENTITY(1,1)")
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("TO_BINARY('{hex}', 'HEX')")
    }

    fn max_insert_rows(&self) -> usize {
        16_384
    }
}

/// `MongoDB` shell syntax. Names are JSON strings (`db.getCollection("a.b")`);
/// the SQL builders are never used for it, so the SQL-only methods return
/// harmless shell text.
impl Dialect for MongoDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Mongodb
    }

    fn quote_ident(&self, ident: &str) -> String {
        serde_json::Value::String(ident.to_owned()).to_string()
    }

    /// A plain JavaScript identifier can follow `db.` directly.
    fn needs_quotes(&self, ident: &str) -> bool {
        let mut chars = ident.chars();
        !(chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
            && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$'))
            || MONGO_RESERVED.contains(&ident)
    }

    fn quote_literal(&self, value: &str) -> String {
        self.quote_ident(value)
    }

    fn placeholder(&self, _index: usize, _column_type: &str) -> String {
        "null".into()
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        quoted_column.to_owned()
    }

    fn comparable(&self, _data_type: &str) -> bool {
        false
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        format!("{{ {quoted_column}: {placeholder} }}")
    }

    fn paginate(&self, sql: &str, _ordered: bool, offset: u64, limit: u64) -> String {
        if offset == 0 { format!("{sql}.limit({limit})") } else { format!("{sql}.skip({offset}).limit({limit})") }
    }

    fn template_placeholder(&self, _n: usize) -> String {
        "null".into()
    }

    /// The adapter runs `BEGIN` / `COMMIT` / `ROLLBACK` on a driver session.
    fn begin_transaction(&self) -> &'static str {
        "BEGIN"
    }

    fn identity_clause(&self) -> Option<&'static str> {
        None
    }

    fn aborts_transaction_on_error(&self) -> bool {
        true
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("BinData(0, \"{hex}\")")
    }

    fn bool_literal(&self, value: bool) -> &'static str {
        if value { "true" } else { "false" }
    }

    /// `db.getCollection("orders")`, or `db.orders` when no quoting is needed.
    fn quoted_name(&self, object: &ObjectRef) -> String {
        format!("db.getCollection({})", self.quote_ident(&object.name))
    }

    fn display_name(&self, object: &ObjectRef) -> String {
        if self.needs_quotes(&object.name) { self.quoted_name(object) } else { format!("db.{}", object.name) }
    }
}

/// `PartiQL` for `DynamoDB`: double-quoted names, single-quoted strings, `?`
/// parameters. There is no `LIMIT`: the adapter pages with the API's tokens.
impl Dialect for PartiqlDialect {
    fn flavor(&self) -> SqlFlavor {
        SqlFlavor::Partiql
    }

    fn quote_ident(&self, ident: &str) -> String {
        format!("\"{}\"", ident.replace('"', "\"\""))
    }

    fn needs_quotes(&self, ident: &str) -> bool {
        let mut chars = ident.chars();
        !(chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
            && chars.all(|c| c.is_ascii_alphanumeric() || c == '_'))
            || is_reserved(ident, PARTIQL_RESERVED)
    }

    fn quote_literal(&self, value: &str) -> String {
        format!("'{}'", value.replace('\'', "''"))
    }

    fn placeholder(&self, _index: usize, _column_type: &str) -> String {
        "?".into()
    }

    fn cast_to_text(&self, quoted_column: &str) -> String {
        quoted_column.to_owned()
    }

    fn comparable(&self, data_type: &str) -> bool {
        matches!(data_type, "S" | "N" | "B")
    }

    fn search_predicate(&self, quoted_column: &str, placeholder: &str) -> String {
        format!("contains({quoted_column}, {placeholder})")
    }

    fn paginate(&self, sql: &str, _ordered: bool, _offset: u64, _limit: u64) -> String {
        sql.to_owned()
    }

    fn template_placeholder(&self, _n: usize) -> String {
        "?".into()
    }

    /// Writes are queued until `COMMIT`, which sends them as one `ExecuteTransaction`.
    fn begin_transaction(&self) -> &'static str {
        "BEGIN"
    }

    fn identity_clause(&self) -> Option<&'static str> {
        None
    }

    fn binary_literal(&self, hex: &str) -> String {
        format!("'{hex}'")
    }

    fn bool_literal(&self, value: bool) -> &'static str {
        if value { "true" } else { "false" }
    }

    /// `ExecuteTransaction` takes at most 100 statements.
    fn max_insert_rows(&self) -> usize {
        1
    }
}

pub fn dialect_for(flavor: SqlFlavor) -> &'static dyn Dialect {
    match flavor {
        SqlFlavor::Postgres => &PostgresDialect,
        SqlFlavor::Mysql => &MysqlDialect,
        SqlFlavor::Sqlserver => &SqlServerDialect,
        SqlFlavor::Oracle => &OracleDialect,
        SqlFlavor::Clickhouse => &ClickhouseDialect,
        SqlFlavor::Duckdb => &DuckdbDialect,
        SqlFlavor::Snowflake => &SnowflakeDialect,
        SqlFlavor::Mongodb => &MongoDialect,
        SqlFlavor::Partiql => &PartiqlDialect,
    }
}

fn join(container: Option<&str>, name: &str, quote: impl Fn(&str) -> String) -> String {
    match container {
        Some(c) => format!("{}.{}", quote(c), quote(name)),
        None => quote(name),
    }
}

fn is_reserved(ident: &str, list: &[&str]) -> bool {
    list.iter().any(|k| k.eq_ignore_ascii_case(ident))
}

