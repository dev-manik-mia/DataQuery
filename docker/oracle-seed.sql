CREATE TABLE customers (
  id         NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email      VARCHAR2(255) NOT NULL UNIQUE,
  created_at TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE orders (
  id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  customer_id NUMBER(19) NOT NULL,
  status      VARCHAR2(20) DEFAULT 'pending' NOT NULL,
  total       NUMBER(12,2) NOT NULL,
  discount    NUMBER(12,2),
  notes       CLOB,
  created_at  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT orders_pkey PRIMARY KEY (id),
  CONSTRAINT orders_customer_fk FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT orders_status_check CHECK (status IN ('pending', 'paid', 'refunded'))
);
CREATE INDEX orders_created_at_idx ON orders (created_at DESC);

CREATE TABLE type_samples (
  id    NUMBER(10) PRIMARY KEY,
  big   NUMBER(19),
  exact NUMBER(38,10),
  ts    TIMESTAMP(3) WITH TIME ZONE,
  day   DATE,
  doc   CLOB,
  raw   RAW(64),
  label VARCHAR2(50),
  ratio BINARY_DOUBLE
);

CREATE TABLE no_pk (a NUMBER, b VARCHAR2(10));

CREATE VIEW paid_orders AS SELECT * FROM orders WHERE status = 'paid';

CREATE SEQUENCE invoice_seq;

CREATE OR REPLACE FUNCTION order_total (p_id NUMBER) RETURN NUMBER AS
  v NUMBER;
BEGIN
  SELECT total INTO v FROM orders WHERE id = p_id;
  RETURN v;
END;
/

CREATE OR REPLACE PROCEDURE touch_order (p_id NUMBER) AS
BEGIN
  UPDATE orders SET status = status WHERE id = p_id;
END;
/

CREATE OR REPLACE TRIGGER orders_touch BEFORE UPDATE ON orders FOR EACH ROW
BEGIN
  :new.status := :new.status;
END;
/

